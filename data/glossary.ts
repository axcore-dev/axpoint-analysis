/** 용어 조회 — 정확히 일치하는 항목 우선, 없으면 포함 매칭 */
export function getGlossary(term: string): GlossaryEntry | undefined {
  const q = term.trim();
  return (
    glossary.find((g) => g.term === q) ??
    glossary.find((g) => g.term.includes(q) || q.includes(g.term))
  );
}
